// Sprache automatisch erkennen
function detectLanguage() {
  const browserLang = navigator.language || navigator.userLanguage;
  const langCode = browserLang.split('-')[0]; // 'de-DE' -> 'de'
  
  // Prüfen ob Sprache verfügbar ist, sonst Fallback zu 'en'
  return translations[langCode] ? langCode : 'en';
}

let currentLang = detectLanguage();

// Translation Funktion
function t(key, replacements = {}) {
  let text = translations[currentLang][key] || translations['en'][key] || key;
  
  // Replacements durchführen (z.B. {name}, {count})
  Object.keys(replacements).forEach(placeholder => {
    text = text.replace(new RegExp(`\\{${placeholder}\\}`, 'g'), replacements[placeholder]);
  });
  
  return text;
}

// Sprache wechseln
function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('language', lang);
    return true;
  }
  return false;
}

// Türkçe fallback: tr eksikse en'den al, varsayılan tr
for (const k in translations.en) if (!(k in translations.tr)) translations.tr[k] = translations.en[k];
translations.tr.title = 'Steamix TV ULTIMATE';
const savedLang = localStorage.getItem('language');
if (savedLang && translations[savedLang]) {
  currentLang = savedLang;
} else if (!savedLang) {
  currentLang = 'tr';
  localStorage.setItem('language','tr');
}

// Export für ES6 Module
window.t = t;
window.setLanguage = setLanguage;
window.currentLang = currentLang;
window.availableLanguages = Object.keys(translations);

console.log(`🌍 Language: ${currentLang}`);
